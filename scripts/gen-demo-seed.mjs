// Generates seed/demo.sql — deterministic DEMO MODE content (fixture imagery, clearly labelled as demo).
// Mirrors worker/demo.ts listDemoFolder() so a later "demo sync" reports zero changes.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { DEFAULT_STYLE, PRESETS, applyPreset } from '../shared/style.ts';

const manifest = JSON.parse(readFileSync('shared/demo-manifest.json', 'utf8'));
const byId = new Map(manifest.images.map((i) => [i.id, i]));
const q = (v) =>
  v === null || v === undefined
    ? 'NULL'
    : typeof v === 'number'
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;
const now = '2026-11-20T09:00:00.000Z';
const out = [
  '-- DEMO MODE seed. Generated by scripts/gen-demo-seed.mjs. Imagery: Unsplash License via picsum.photos.',
  'PRAGMA defer_foreign_keys = true;',
  "DELETE FROM collections WHERE source = 'demo';",
  `UPDATE studio_settings SET studio_name = 'lensasamsol', intro = 'Wedding, portrait and event photography. Every gallery is delivered privately to its client by link.', contact_url = 'mailto:studio@example.com', contact_label = 'Commissions', updated_at = ${q(now)} WHERE id = 1;`,
];

function files(key) {
  const set = manifest.sets[key];
  if (key === 'archive') {
    return Array.from({ length: 1200 }, (_, k) => {
      const img = manifest.images[(k * 7) % manifest.images.length];
      return { fileId: `demo-${img.id}-${k}`, name: `DSC_${String(k + 1).padStart(4, '0')}.jpg`, img };
    });
  }
  if (!set) return [];
  return set.map((id, k) => ({
    fileId: `demo-${id}`,
    name: `DSC_${String(k + 1).padStart(4, '0')}.jpg`,
    img: byId.get(String(id)),
  }));
}

let photoSeq = 0;
function collection(def) {
  const preset = PRESETS.find((p) => p.id === def.preset);
  let style = applyPreset(DEFAULT_STYLE, preset);
  style = {
    ...style,
    ...def.style,
    cover: { ...style.cover, ...(def.style?.cover ?? {}) },
    layout: { ...style.layout, ...(def.style?.layout ?? {}) },
  };
  const styleJson = JSON.stringify(style);
  const list = files(def.folder);
  const ids = list.map(() => `ph_demo${String(++photoSeq).padStart(6, '0')}`);
  const coverIdx = def.cover ? list.findIndex((f) => f.img.id === String(def.cover)) : -1;
  const cover = coverIdx >= 0 ? ids[coverIdx] : (ids[0] ?? null);
  const published = def.status === 'published';
  out.push(
    `INSERT INTO collections (id, slug, title, client_name, share_token, share_token_created_at, assignment_mode, description, event_date, location, source, drive_folder_id, drive_folder_name, folder_access, cover_photo_id, status, homepage_visible, style_draft_json, style_published_json, style_draft_updated_at, style_published_at, sync_status, sync_error, last_synced_at, photo_count, hidden_count, created_at, updated_at, published_at) VALUES (` +
      [
        def.id,
        def.slug,
        def.title,
        def.client ?? null,
        randomBytes(18).toString('base64url'), // fresh, unguessable client link on every seed
        now,
        def.assign ? 'selected' : 'all',
        def.description ?? null,
        def.date ?? null,
        def.location ?? null,
        'demo',
        def.folder,
        def.folderName,
        'unknown',
        cover,
        def.status,
        def.homepage === false ? 0 : 1,
        styleJson,
        published ? styleJson : null,
        now,
        published ? now : null,
        def.syncStatus ?? (list.length ? 'synced' : 'never'),
        def.syncError ?? null,
        list.length || def.syncStatus === 'error' ? now : null,
        0,
        0,
        now,
        def.updated ?? now,
        published ? now : null,
      ]
        .map(q)
        .join(', ') +
      ');',
  );
  const rows = list.map((f, k) => {
    // 'selected' galleries (shared folder): only the listed fixtures are assigned to this client.
    const assigned = def.assign
      ? def.assign.includes(Number(f.img.id))
      : !def.hidden?.includes(Number(f.img.id));
    const featured = assigned && def.featured?.includes(Number(f.img.id)) && k < 400 ? 1 : 0;
    return `(${[ids[k], def.id, f.fileId, f.name, 'image/jpeg', f.img.width, f.img.height, 1, k, assigned ? 0 : 1, assigned ? 1 : 0, featured, featured ? def.featured.indexOf(Number(f.img.id)) + 1 : null, 'fixture-1', null, null, null, f.img.id, JSON.stringify({ author: f.img.author, url: f.img.sourceUrl }), 0, now, now].map(q).join(', ')})`;
  });
  if (def.brokenPreview) {
    rows.push(
      `(${[`ph_demo${String(++photoSeq).padStart(6, '0')}`, def.id, 'demo-missing', 'DSC_9999.jpg', 'image/jpeg', 1600, 1067, 1, list.length, 0, 1, 0, null, 'fixture-1', null, null, null, 'missing-asset', null, 0, now, now].map(q).join(', ')})`,
    );
  }
  for (let i = 0; i < rows.length; i += 200) {
    out.push(
      `INSERT INTO photos (id, collection_id, drive_file_id, filename, mime_type, width, height, dims_known, sort_order, hidden, assigned, featured, featured_order, source_version, modified_time, view_url, resource_key, demo_asset, demo_credit, unavailable, created_at, updated_at) VALUES\n${rows.slice(i, i + 200).join(',\n')};`,
    );
  }
  out.push(
    `UPDATE collections SET photo_count = (SELECT COUNT(*) FROM photos WHERE collection_id = ${q(def.id)} AND assigned = 1 AND unavailable = 0), hidden_count = (SELECT COUNT(*) FROM photos WHERE collection_id = ${q(def.id)} AND assigned = 0) WHERE id = ${q(def.id)};`,
  );
  out.push(
    `INSERT INTO sync_runs (id, collection_id, trigger, started_at, finished_at, status, added, error) VALUES (${[`sync_seed_${def.id}`, def.id, 'demo-seed', now, now, def.syncStatus === 'error' ? 'error' : 'success', def.syncStatus === 'error' ? 0 : list.length, def.syncError ?? null].map(q).join(', ')});`,
  );
}

